-- Idempotent repair for production upload recovery telemetry.
-- The original 20260819 migration was not applied to production because the
-- guarded migration workflow stopped before `supabase db push`.

create table if not exists public.admin_upload_operations (
  id bigint generated by default as identity primary key,
  batch_id text,
  upload_id text,
  phase text not null,
  status text not null,
  storage_path text,
  file_name text,
  file_size bigint,
  error_code text,
  error_message text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.admin_upload_operations add column if not exists batch_id text;
alter table public.admin_upload_operations add column if not exists upload_id text;
alter table public.admin_upload_operations add column if not exists phase text;
alter table public.admin_upload_operations add column if not exists status text;
alter table public.admin_upload_operations add column if not exists storage_path text;
alter table public.admin_upload_operations add column if not exists file_name text;
alter table public.admin_upload_operations add column if not exists file_size bigint;
alter table public.admin_upload_operations add column if not exists error_code text;
alter table public.admin_upload_operations add column if not exists error_message text;
alter table public.admin_upload_operations add column if not exists metadata jsonb default '{}'::jsonb;
alter table public.admin_upload_operations add column if not exists created_at timestamptz default now();

update public.admin_upload_operations set metadata = '{}'::jsonb where metadata is null;

create index if not exists admin_upload_operations_batch_idx
  on public.admin_upload_operations (batch_id, created_at desc);
create index if not exists admin_upload_operations_upload_idx
  on public.admin_upload_operations (upload_id, created_at desc);
create index if not exists admin_upload_operations_phase_status_idx
  on public.admin_upload_operations (phase, status, created_at desc);

alter table public.admin_upload_operations enable row level security;

